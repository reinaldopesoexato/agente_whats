const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const os=require('node:os')
const {setTimeout:delay}=require('node:timers/promises')
const {createMessageArchive}=require('./message-archive')
test('prévia e exclusão manual preservam texto, contas e anexos recentes e impedem recaptura',async t=>{
  const dir=fs.mkdtempSync(path.join(os.tmpdir(),'midias-'))
  t.after(()=>fs.rmSync(dir,{recursive:true,force:true}))
  const archive=createMessageArchive(dir,()=>({mediaDays:1}))
  function save(id,days,account='a',mime='image/png'){
    archive.capture(account,{id,from:'123@c.us',timestamp:Date.now()/1000-days*86400,body:'legenda',type:'image',hasMedia:true,
      downloadMedia:async()=>({mimetype:mime,data:'YWJj'})})
  }
  save('antiga',100);save('recent',2);save('outra',100,'b');save('som',100,'a','audio/ogg')
  for(let i=0;i<50&&!archive.original('a','som').media;i++)await delay(10)
  await archive.scan({prune:true})
  const plan=await archive.preview({days:90,type:'image',account:'a'})
  assert.equal(plan.count,1);assert.equal(plan.bytes,3)
  save('depois-da-previa',95)
  assert.deepEqual(await archive.clean(plan.ticket),{count:1,bytes:3})
  await assert.rejects(archive.clean(plan.ticket))
  save('antiga',100)
  assert.equal(archive.original('a','antiga').record.body,'legenda')
  assert.equal(archive.original('a','antiga').media,null)
  assert(archive.removed('a','antiga'));assert(archive.original('b','outra').media)
  await delay(40)
  assert.equal((await archive.preview({days:90,type:'image',account:'a'})).count,1)
})
